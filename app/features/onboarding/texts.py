from dataclasses import dataclass

QUICK_CONNECT_LABEL = "Подключить сразу"


@dataclass(frozen=True, slots=True)
class OnboardingStep:
    """Один экран воронки.

    Attributes:
        text: Текст экрана (HTML-разметка).
        next_index: Индекс следующего шага для кнопки «Далее →»; ``None`` —
            на шаге нет перехода вперёд (последний экран).
        show_quick_connect: Показать вторичную кнопку «Подключить сразу» для
            замотивированных пользователей.
        cta_token_label: Если задано — на шаге есть основная кнопка перехода к
            вводу токена с этим текстом (используется на последнем экране).

    """

    text: str
    next_index: int | None
    show_quick_connect: bool
    cta_token_label: str | None


