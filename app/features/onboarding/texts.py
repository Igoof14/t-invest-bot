"""Контент онбординг-воронки: экраны как данные.

Воронка построена по схеме PAS (Problem → Agitate → Solve) + снятие
возражений + CTA без трения. Каждый шаг — отдельный экран карусели, который
рендерится поверх предыдущего (``edit_text``).

Текст использует HTML-разметку (``<b>`` для жирного), как и остальные
сообщения бота, чтобы тон был единым.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class OnboardingStep:
    """Один экран воронки.

    Attributes:
        text: Текст экрана (HTML-разметка).
        next_index: Индекс следующего шага для кнопки «Далее →»; ``None`` —
            на шаге нет перехода вперёд (последний экран).
        cta_token_label: Если задано — на шаге есть кнопка перехода к вводу
            токена с этим текстом (используется на последнем экране).
        cta_market_label: Если задано — на шаге есть кнопка «работать без
            токена» с этим текстом. Вместе с ``cta_token_label`` образует
            развилку режимов на последнем экране.

    """

    text: str
    next_index: int | None
    cta_token_label: str | None
    cta_market_label: str | None = None


