"""Область применения алерта: портфель пользователя или весь рынок.

Продюсеры событий делят получателей на две аудитории. У пользователя с
подключённым токеном есть портфель, поэтому событие уже отфильтровано по его
бумагам — ``PORTFOLIO``. У пользователя без токена портфеля нет, и он получает
события по всему рынку — ``MARKET``.

Поле приезжает в payload события и влияет только на текст сообщения: логика
доставки для обеих аудиторий одинаковая.
"""

from __future__ import annotations

from enum import StrEnum


class AlertScope(StrEnum):
    """Аудитория, которой адресовано событие."""

    PORTFOLIO = "portfolio"
    """Пользователь с токеном: событие касается его бумаг."""

    MARKET = "market"
    """Пользователь без токена: событие по всему рынку."""

    @property
    def is_market(self) -> bool:
        """Нужно ли пояснять, что событие не про портфель пользователя."""
        return self is AlertScope.MARKET


# Приписка к рыночным уведомлениям: объясняет, почему пришла незнакомая бумага,
# и показывает выход. Одна строка — сообщения и так длинные.
MARKET_HINT = (
    "<i>Событие по всему рынку. Подключите токен в «Настройках», "
    "чтобы получать только по своим бумагам.</i>"
)


def with_market_hint(text: str, scope: AlertScope) -> str:
    """Добавляет пояснение про рыночный режим, если событие не про портфель."""
    if not scope.is_market:
        return text
    return f"{text}\n\n{MARKET_HINT}"
